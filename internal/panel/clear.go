package panel

import "io"

// clearSeq — курсор в начало экрана и стирание экрана.
const clearSeq = "\x1b[H\x1b[2J"

// ClearScreen очищает экран терминала w перед стартом панели: панель и строки
// запуска начинаются с чистого окна. Не tea.ClearScreen: без полноэкранного режима
// он перерисовывает только область самой панели, а то, что выше неё, остаётся.
// Ошибка записи не важна: в худшем случае панель стартует под прежними строками.
func ClearScreen(w io.Writer) {
	_, _ = io.WriteString(w, clearSeq)
}
